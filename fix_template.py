import json

path = "flowable-provisioning-workflow.json"

with open(path, "r", encoding="utf-8") as f:
    workflow = json.load(f)

for node in workflow["nodes"]:
    if node["name"] == "Check Secret":
        conditions = node["parameters"]["conditions"]

        conditions["combinator"] = "or"

        conditions["conditions"] = [
            {
                "id": "check-secret-bypass",
                "leftValue": "={{ $env.PROVISIONING_SECRET_REQUIRED || 'true' }}",
                "rightValue": "false",
                "operator": {
                    "type": "string",
                    "operation": "equals"
                }
            },
            {
                "id": "check-secret-header",
                "leftValue": "={{ $json.headers['x-provisioning-key'] }}",
                "rightValue": "={{ $env.PROVISIONING_SECRET }}",
                "operator": {
                    "type": "string",
                    "operation": "equals"
                }
            }
        ]

    elif node["name"] == "Read Me":
        node["parameters"]["content"] = """## Account Provisioning Template

This is the shared base workflow for account provisioning.

Before using this template:
- Set PROVISIONING_SECRET in the local n8n environment.
- Keep PROVISIONING_SECRET_REQUIRED=true by default.
- A local-only bypass is available by setting PROVISIONING_SECRET_REQUIRED=false.
- Never use the bypass on shared, dev, or sandbox instances.

Customize the "Create Account" node for the target tool, then activate the workflow and configure its webhook URL in the Tool Registry.

The password is generated by the application and included in the request body as password. Use it when creating the account instead of generating your own.

See docs/provisioning/README.md in the app repo for the full request/response contract."""

with open(path, "w", encoding="utf-8") as f:
    json.dump(workflow, f, indent=2)
    f.write("\n")

print("Template updated successfully.")
